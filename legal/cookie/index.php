<p>Cookie-файлы относятся к одной из технологий, которые мы используем для автоматического сбора информации и повышения качества контента. Так же, как и большинство других организаций, занимающихся информационными ресурсами, наши веб-серверы и системы безопасности время от времени хранят некоторые временные технические данные в своих лог-файлах.</p>
<p>Собираемые cookie-файлы на нашем сайте:</p>

<p><strong>Сессионные</strong></p>
<p>Существуют только во временной памяти в течение времени, когда пользователь находится на странице веб-сайта. Обычно сессионные cookie-файлы удаляют после того, как Вы закрываете окно веб-сайта. Сессионные cookie-файлы позволяют помнить информацию о Вашем выборе на предыдущей странице, чтобы избежать необходимости повторного ввода информации.</p>

<p><strong>Постоянные</strong></p>
<p>Cookie-файлы, которые хранятся на Вашем компьютере или мобильном устройстве и не удаляются при закрытии браузера. Постоянные cookie-файлы могут сохранять пользовательские настройки для определённого веб-сайта, позволяя использовать эти предпочтения в будущих сеансах использования веб-сайта.</p>
