<p><strong>Аналитические/маркетинговые</strong></p>
<p>Включают в себя информацию о том, как Вы используете веб-сайт, например, какие страницы Вы посещаете, по каким ссылкам переходите. Мы используем эти cookie-файлы, в основном для того, чтобы улучшить функционал веб-сайта и Ваш пользовательский опыт при его использовании. Иногда такие cookie-файлы также позволяют нам определить Ваши предпочтения и предоставить Вам полезную целевую информацию по продуктам, услугам и сервисам, которые могут Вас заинтересовать.</p>

